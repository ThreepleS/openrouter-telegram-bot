def translate_api_error(status_code: int | None, message: str | None) -> str | None:
    if status_code is not None:
        key = str(status_code)
        if key in API_ERROR_TRANSLATIONS:
            return API_ERROR_TRANSLATIONS[key]

    if message:
        lower_msg = message.lower()
        for error_key, translation in API_ERROR_TRANSLATIONS.items():
            if error_key.lower() in lower_msg:
                return translation

    return None


def format_api_error(status_code: int | None, error_message: str | None) -> str:
    parts: list[str] = []
    if status_code is not None:
        parts.append(f"❌ Ошибка API ({status_code}): {error_message or 'Нет дополнительной информации'}")
    else:
        parts.append(f"❌ Ошибка API: {error_message or 'Нет дополнительной информации'}")

    translation = translate_api_error(status_code, error_message)
    if translation:
        parts.append(f"\n💡 {translation}")

    return "\n".join(parts)
